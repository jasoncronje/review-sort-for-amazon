#!/usr/bin/env python3
"""Builds brands.js (the "no-name brand" list) from data/amazon_brand_candidates_1000.csv.

Each brand and its observed spellings are normalized the same way content.js does it:
uppercase, letters and digits only ("X XINDELL" -> "XXINDELL")."""
import csv, json, re, os
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "data", "amazon_brand_candidates_1000.csv")
norm = lambda s: re.sub(r"[^A-Z0-9]", "", s.upper())
names = set()
with open(src, encoding="utf-8-sig") as f:
    for row in csv.DictReader(f):
        for s in [row["brand"], row["normalized_brand"], row["amazon_brand_value"], *row["observed_name_variants"].split(";")]:
            n = norm(s)
            if len(n) >= 3:
                names.add(n)
with open(os.path.join(here, "brands.js"), "w") as f:
    f.write("// Generated by gen-brands.py from data/amazon_brand_candidates_1000.csv. Do not edit.\n")
    f.write(f"globalThis.RSA_NO_NAME_BRANDS = {json.dumps('|'.join(sorted(names)))};\n")
print(len(names), "brand spellings")
