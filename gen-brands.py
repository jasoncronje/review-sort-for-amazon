#!/usr/bin/env python3
"""Builds brands.js for the "Hide no-name brands" filter from three inputs in data/:

  amazon_brand_candidates_1000.csv  1,000 brands seen most in Amazon reviews (hand-curated list)
  cn_trademarks.txt.gz              ~717k China-owned US trademark names (tools/fetch-trademarks.py)
  keep-brands.txt                   well-known brands that are never hidden

The big list ships as a Bloom filter (about 1 false hit in 10,000 lookups) so it fits in
~2 MB. content.js hashes the same way: FNV-1a 32-bit with two seeds, double hashing.
Names are matched as uppercase letters/digits words joined by one space ("X XINDELL").
"""
import base64, csv, gzip, json, math, os, re
here = os.path.dirname(os.path.abspath(__file__))
data = lambda f: os.path.join(here, "data", f)
words = lambda s: re.findall(r"[A-Z0-9]+", s.upper())
spaced = lambda s: " ".join(words(s))
squashed = lambda s: "".join(words(s))

curated = set()
with open(data("amazon_brand_candidates_1000.csv"), encoding="utf-8-sig") as f:
    for row in csv.DictReader(f):
        for s in [row["brand"], row["normalized_brand"], row["amazon_brand_value"], *row["observed_name_variants"].split(";")]:
            if len(squashed(s)) >= 3: curated.add(squashed(s))
keep = {squashed(l) for l in open(data("keep-brands.txt")) if l.strip() and not l.startswith("#")}
with gzip.open(data("cn_trademarks.txt.gz"), "rt") as f:
    marks = [l.strip() for l in f if l.strip()]
marks = [m for m in marks if squashed(m) not in keep]

def fnv(s, seed):
    h = seed
    for b in s.encode():
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h
P = 1e-4
n = len(marks)
m = math.ceil(-n * math.log(P) / math.log(2) ** 2 / 8) * 8
k = round(m / n * math.log(2))
bits = bytearray(m // 8)
for s in marks:
    h1, h2 = fnv(s, 2166136261), fnv(s, 0x9747B28C) | 1
    for i in range(k):
        p = (h1 + i * h2) % m
        bits[p >> 3] |= 1 << (p & 7)

with open(os.path.join(here, "brands.js"), "w") as f:
    f.write("// Generated by gen-brands.py from data/. Do not edit.\n")
    f.write(f"globalThis.RSA_NO_NAME_BRANDS = {json.dumps('|'.join(sorted(curated - keep)))};\n")
    f.write(f"globalThis.RSA_KEEP_BRANDS = {json.dumps('|'.join(sorted(keep)))};\n")
    f.write(f"globalThis.RSA_CN_MARKS = {{ m: {m}, k: {k}, n: {n}, bits: \"{base64.b64encode(bits).decode()}\" }};\n")
print(f"{len(curated - keep)} curated, {len(keep)} kept, {n} trademark names -> {m // 8 // 1024} KB filter, k={k}")
