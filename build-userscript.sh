#!/bin/sh
# Builds review-sort.user.js (for Ardia / Violentmonkey) from brands.js + content.js + styles.css.
set -e
cd "$(dirname "$0")"
out=review-sort.user.js
{
  echo "// ==UserScript=="
  echo "// @name         Review Sort for Amazon"
  echo "// @namespace    review-sort-amazon"
  echo "// @version      $(python3 -c 'import json;print(json.load(open("manifest.json"))["version"])')"
  echo "// @description  Sort Amazon search results by reviews, rating or weighted score across pages."
  python3 -c 'import json
for m in json.load(open("manifest.json"))["content_scripts"][0]["matches"]: print("// @match        " + m)'
  echo "// @run-at       document-idle"
  echo "// @noframes"
  echo "// @grant        none"
  echo "// ==/UserScript=="
  echo "// Generated by build-userscript.sh. Edit content.js / styles.css instead."
  printf '(() => { const s = document.createElement("style"); s.textContent = %s; (document.head || document.documentElement).appendChild(s); })();\n' \
    "$(python3 -c 'import json;print(json.dumps(open("styles.css").read()))')"
  cat brands.js content.js
} > "$out"
echo "built $out"
